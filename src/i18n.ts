export const STRINGS = { DE, FR, IT, EN };

export type MessageKey = keyof typeof DE;

export function t(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  let text: string = STRINGS[lang][key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function htmlLang(lang: Lang): string {
  return lang.toLowerCase();
}

export function describeError(lang: Lang, error: { field: string; code: string; max?: number }): string {
  const fieldKey = `err.field.${error.field}` as MessageKey;
  const codeKey = `err.${error.code}` as MessageKey;
  const dictionary = STRINGS[lang];
  const fieldName = fieldKey in dictionary ? dictionary[fieldKey] : error.field;
  const message = codeKey in dictionary ? t(lang, codeKey, { max: error.max ?? "" }) : error.code;
  return `${fieldName}: ${message}`;
}
